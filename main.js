function updatePosition() {

  leftCurrentYRatio =
    Math.min(
      1,
      Math.max(0, leftCurrentYRatio)
    );

  leftCurrentSize =
    TOP_SIZE +
    (BOTTOM_SIZE - TOP_SIZE) *
    leftCurrentYRatio;

  const currentLeft =
    leftlerp(
      TOP_POS.left,
      BOTTOM_POS.left,
      leftCurrentYRatio
    );

  const currentBottom =
    leftlerp(
      TOP_POS.bottom,
      BOTTOM_POS.bottom,
      leftCurrentYRatio
    );

  let verticalScale;

  if (isIPad) {

  verticalScale =
    leftlerp(0.7, 1.0, leftCurrentYRatio);

  } else {

  verticalScale =
    leftlerp(0.7, 1.0, leftCurrentYRatio);
  }

  // ======================================
  // 左手画像更新
  // ======================================

  leftPhoto.style.width =
    `${leftCurrentSize}px`;

  leftPhoto.style.left =
    `${currentLeft}%`;

  leftPhoto.style.bottom =
    `${currentBottom}%`;

  leftPhoto.style.transform =
    `scaleY(${verticalScale})`;

  // ======================================
  // 音量メータ更新
  // ======================================

  if (
    volumeLevel &&
    volumeValueDisplay &&
    volumeIconOn &&
    volumeIconOff
  ) {

    const volumeRatio =
      1 - leftCurrentYRatio;

    // バー高さ
    if (isStart) {

      volumeLevel.style.transform =
        `scaleY(${volumeRatio})`;

    } else {

      volumeLevel.style.transform =
        `scaleY(0)`;
    }

    // 数値
    const volumePercent =
      Math.round(volumeRatio * 100);

    if (isStart) {

      volumeValueDisplay.textContent =
        volumePercent;

    } else {

      volumeValueDisplay.textContent =
        0;
    }

    // アイコン切替
    if (
      volumePercent > 0 &&
      isStart
    ) {

      volumeIconOn.style.display =
        'block';

      volumeIconOff.style.display =
        'none';

    } else {

      volumeIconOn.style.display =
        'none';

      volumeIconOff.style.display =
        'block';
    }
  }
}


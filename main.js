// アニメーション
// ========================================

function animate() {

  if (isIPad) {

    leftCurrentYRatio +=
      (leftTargetYRatio - leftCurrentYRatio) * 0.2;
  }

  if (!isDPress) {

    if (moveUp)
      leftCurrentYRatio -= moveSpeed;

    if (moveDown)
      leftCurrentYRatio += moveSpeed;
  }

  updatePosition();

  requestAnimationFrame(animate);
}

